/**
 * Domain contracts used by the UI. These are camelCase, frontend-owned shapes.
 * Wire formats (snake_case DTOs) live in ./dto.ts and are mapped by the HTTP adapter,
 * so a backend payload change only touches the adapter.
 */

export interface ModelOption {
  id: string; // physical model name, e.g. "nvidia/Qwen3.6-35B-A3B-NVFP4"
  label: string; // display label from [llm_models] in config.toml
  isDefault: boolean;
}

export interface Collection {
  name: string;
  documentCount: number;
}

export interface AppConfig {
  models: ModelOption[];
  uploadAccept: string[]; // file extensions without dot
  maxUploadBytes: number;
  excerptChars: number; // mirrors [streamlit.chat].excerpt_chars
  conversationTitleMaxChars: number;
  features: { driveImport: boolean; cancelTurn: boolean };
}

export interface DocumentMeta {
  id: string;
  collection: string;
  name: string;
  extension: string; // upper case, e.g. "PDF"
  relativePath: string;
  sizeBytes?: number;
  updatedAt?: string; // ISO 8601
  summary?: string; // e.g. "32 p." — optional backend hint
}

export interface FocusSpan {
  start: number;
  end: number;
  quote: string;
  claimIds: string[];
}

/** One cited source, mirroring the output of Sources.normalize_presentation(). */
export interface Source {
  sourceId: string;
  evidenceId: string;
  documentName: string;
  chunkKind: string;
  sectionTitle: string;
  excerpt: string;
  relativePath: string;
  pages: number[];
  claimIds: string[];
  focusSpans: FocusSpan[];
  documentId?: string;
}

export interface Claim {
  claimId: string;
  text: string;
  evidenceIds: string[];
}

/** Final turn states produced by presentation/chat/Turns.run(). */
export type AnswerState = 'answered' | 'partial' | 'casual' | 'abstained' | 'clarification_required';

export interface UserMessage {
  id: string;
  role: 'user';
  content: string;
  turnId?: string;
  createdAt: string;
}

export interface AssistantMessage {
  id: string;
  role: 'assistant';
  turnId?: string; // absent on legacy messages
  content: string;
  claims: Claim[];
  sources: Source[];
  state: AnswerState;
  route: string; // "retrieval" shows sources, other routes do not
  model?: { id: string; label: string };
  collections: string[];
  durationMs?: number;
  warnings: string[];
  execution?: Record<string, unknown>;
  createdAt: string;
}

export type Message = UserMessage | AssistantMessage;

export interface ConversationSummary {
  id: string;
  title: string;
  updatedAt: string;
  collections: string[];
  model?: string;
}

export interface AskRequest {
  conversationId: string;
  clientTurnId: string; // idempotency key generated by the client
  question: string;
  modelId: string;
  collections: string[];
}

/**
 * Stream events for one turn. The HTTP adapter decodes SSE frames into these.
 * Stage ids are open-ended so the backend can add stages without breaking the UI.
 */
export type TurnEvent =
  | { type: 'accepted'; turnId: string; userMessageId?: string }
  | { type: 'progress'; stage: string; label?: string; current?: number; total?: number }
  | { type: 'delta'; text: string }
  | { type: 'completed'; message: AssistantMessage }
  | { type: 'failed'; error: TurnFailure };

export interface TurnFailure {
  /** "unknown" = the remote result is uncertain; the question must not be resent automatically. */
  outcome: 'failed' | 'unknown';
  message: string;
  code?: string;
}

export type UploadPhase = 'queued' | 'uploading' | 'extracting' | 'indexing' | 'done' | 'skipped' | 'error';

export interface UploadProgress {
  fileName: string;
  phase: UploadPhase;
  /** 0–100 within the whole pipeline for this file. */
  percent: number;
  message?: string;
}

export interface UploadResult {
  saved: DocumentMeta[];
  skipped: { fileName: string; reason: string }[];
}
